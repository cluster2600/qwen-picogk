BG, INK, MUTED, GRID = '#f6f8fa', '#193341', '#486270', '#dde3e8'
BLUE, ORANGE, GREEN = '#2a78d6', '#eb6834', '#1baf7a'     # validated categorical slots 1-3
OVERHANG = '#d1495b'                                      # same flag colour as channel-section.png
SOLID = '#4b6b7a'
COS45 = np.cos(np.pi / 4)
LIGHT = np.array([0.35, -0.55, 0.76]) / np.linalg.norm([0.35, -0.55, 0.76])
EVIDENCE = 'evidence/dfam-code/strict-v3-20261019.json'
AXES = {'x': 0, 'y': 1, 'z': 2}


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def load_stl(path):
    raw = np.fromfile(path, dtype=np.uint8)[84:]
    record = np.dtype([('n', '<f4', 3), ('v', '<f4', (3, 3)), ('a', '<u2')])
    return np.frombuffer(raw.tobytes(), dtype=record)['v'].astype(np.float64)


def fresh(path):
    if path.exists() or path.with_suffix('.json').exists():
        raise SystemExit(f'{path} exists; never overwrite published figures')
    return path


def receipt(path, sources, **extra):
    record = {
        'image': path.name, 'image_sha256': sha(path),
        'sources_sha256': {k: sha(v) for k, v in sources.items()},
        'render_source_sha256': sha(__file__),
        'renderer': f'matplotlib {matplotlib.__version__}, Pillow {pillow_version}, numpy {np.__version__}, '
                    f'scipy {scipy_version}, libigl fast_winding_number',
        'native_geometry_edited_for_render': False, 'evidence': EVIDENCE,
        'synthetic_fixtures': True, 'manufacturing_qualified': False, **extra}
    path.with_suffix('.json').write_text(json.dumps(record, indent=1, sort_keys=True) + '\n')


def outward_normals(tris):
    cross = np.cross(tris[:, 1] - tris[:, 0], tris[:, 2] - tris[:, 0])
    signed = np.einsum('ij,ij->i', tris[:, 0], np.cross(tris[:, 1], tris[:, 2])).sum()
    cross *= 1 if signed >= 0 else -1
    length = np.linalg.norm(cross, axis=1)
    return cross / np.where(length > 0, length, 1)[:, None]


def proxy(tris, cell):
    """Vertex clustering for display: merge vertices per cell, drop collapsed faces."""
    keys = np.floor(tris.reshape(-1, 3) / cell).astype(np.int64)
    _, inverse = np.unique(keys, axis=0, return_inverse=True)
    inverse = inverse.reshape(-1)
    faces = inverse.reshape(-1, 3)
    keep = (faces[:, 0] != faces[:, 1]) & (faces[:, 1] != faces[:, 2]) & (faces[:, 0] != faces[:, 2])
    sums = np.zeros((inverse.max() + 1, 3))
    np.add.at(sums, inverse, tris.reshape(-1, 3))
    centres = sums / np.bincount(inverse)[:, None]
    return centres[faces[keep]], keep


def shade(rgba, tris):
    light = 0.55 + 0.45 * np.clip(outward_normals(tris) @ LIGHT, 0, 1)
    out = np.array(rgba, dtype=float)
    out[:, :3] *= light[:, None]
    return out


def cut(tris, axis, value):
    """Segments where the plane coordinate[axis] = value cuts each triangle, in the other two axes."""
    k = AXES[axis]
    other = [i for i in range(3) if i != k]
    d = tris[:, :, k] - value
    hit = np.nonzero((d.min(1) < 0) & (d.max(1) > 0))[0]
    segs, faces = [], []
    for i in hit:
        pts = []
        for a, b in ((0, 1), (1, 2), (2, 0)):
            if (d[i, a] < 0) != (d[i, b] < 0):
                s = d[i, a] / (d[i, a] - d[i, b])
                pts.append((tris[i, a] + s * (tris[i, b] - tris[i, a]))[other])
        if len(pts) == 2:
            segs.append((*pts[0], *pts[1]))
            faces.append(i)
    return np.array(segs), np.array(faces, dtype=int)


class Solid:
    """An STL as triangles plus an indexed copy for winding-number queries."""

    def __init__(self, path):
        self.tris = load_stl(path)
        vertices, inverse = np.unique(self.tris.reshape(-1, 3), axis=0, return_inverse=True)
        self.V, self.F = vertices, inverse.reshape(-1, 3).astype(np.int64)

    def fill(self, axis, value, extent, pixel):
        """True where the plane coordinate[axis] = value lies inside the solid."""
        k = AXES[axis]
        other = [i for i in range(3) if i != k]
        u0, u1, v0, v1 = extent
        grid_u, grid_v = np.meshgrid(np.arange(u0 + pixel / 2, u1, pixel), np.arange(v0 + pixel / 2, v1, pixel))
        query = np.empty((grid_u.size, 3))
        query[:, other[0]], query[:, other[1]], query[:, k] = grid_u.ravel(), grid_v.ravel(), value
        return (igl.fast_winding_number(self.V, self.F, query) > 0.5).reshape(grid_u.shape)


def frame(axis, extent, xlabel, ylabel, title):
    axis.set_facecolor(BG)
    axis.set_xlim(extent[0], extent[1]); axis.set_ylim(extent[2], extent[3]); axis.set_aspect('equal')
    axis.set_xlabel(xlabel, color=MUTED, fontsize=9); axis.set_ylabel(ylabel, color=MUTED, fontsize=9)
    axis.tick_params(colors=MUTED, labelsize=8)
    for side in axis.spines.values():
        side.set_color(GRID)
    axis.set_title(title, color=INK, fontsize=10.5, loc='left')


def show_fill(axis, image, extent, colour, alpha=1.0):
    rgba = np.zeros((*image.shape, 4))
    rgba[image] = colors.to_rgba(colour, alpha)
    axis.imshow(rgba, origin='lower', extent=extent, interpolation='nearest', zorder=2)


def channel_faces(tris, polyline, radius):
    """Faces whose centroid lies within radius of the channel centre polyline."""
    c = tris.mean(1)
    best = np.full(len(c), np.inf)
    for p, q in zip(polyline[:-1], polyline[1:]):
        t = np.clip(((c - p) @ (q - p)) / ((q - p) @ (q - p)), 0, 1)
        best = np.minimum(best, np.linalg.norm(c - (p + t[:, None] * (q - p)), axis=1))
    return best < radius


MANIFOLD_PATH = [np.array(v, float) for v in ((-30, -8, 8), (8, -8, 8), (8, -8, 22), (8, 22, 22))]
MANIFOLD_BRANCH = [np.array(v, float) for v in ((8, -8, 8), (8, 8, 8))]


def fixture_families(fixtures, out):
    path = fresh(out / 'fixture-families.png')
    names = [('', 'part.stl', 'Slab', 'bored boss and pin boss\n(the original fixture)'),
             ('bracket', 'bracket/part.stl', 'Bracket', '2 mm web, 12 mm horizontal lip,\n0.8 mm rib, 6.4 mm hole'),
             ('manifold', 'manifold/part.stl', 'Manifold',
              '6 mm L-shaped internal channel\nand a blind branch (blue)')]
    figure = plt.figure(figsize=(12, 4.6), dpi=128, facecolor=BG)
    sources = {}
    for i, (family, rel, title, note) in enumerate(names):
        tris = load_stl(fixtures / rel)
        sources[rel] = fixtures / rel
        view, keep = proxy(tris, 0.8)
        axis = figure.add_axes((i / 3, 0.16, 1 / 3, 0.72), projection='3d', facecolor=BG)
        lo, hi = view.reshape(-1, 3).min(0), view.reshape(-1, 3).max(0)
        centre, span = (lo + hi) / 2, (hi - lo).max() * 0.55
        for setter, c in zip((axis.set_xlim, axis.set_ylim, axis.set_zlim), centre):
            setter(c - span, c + span)
        axis.set_box_aspect((1, 1, 1), zoom=1.25)
        axis.set_axis_off()
        base = np.tile(colors.to_rgba('#9fb8c4'), (len(view), 1))
        if family == 'manifold':
            inner = channel_faces(view, MANIFOLD_PATH, 3.6) | channel_faces(view, MANIFOLD_BRANCH, 3.6)
            base[~inner] = colors.to_rgba('#9fb8c4', 0.12)
            base[inner] = colors.to_rgba(BLUE)
        axis.add_collection3d(Poly3DCollection(view, facecolors=shade(base, view), edgecolors='none'))
        axis.view_init(elev=24, azim=-60)
        meta = json.loads((fixtures / (f'{family}/fixture.json' if family else 'fixtures.json')).read_text())
        figure.text((i + 0.5) / 3, 0.9, title, ha='center', color=INK, fontsize=12, fontweight='bold')
        figure.text((i + 0.5) / 3, 0.03, f"{note}\n{meta['volume_mm3']:,.0f} mm3, scan cloud of {meta['scan_points']:,} points",
                    ha='center', color=MUTED, fontsize=9)
    figure.savefig(path, facecolor=BG); plt.close(figure)
    receipt(path, sources, display_proxy={'method': 'vertex clustering for display only', 'cell_mm': 0.8},
            note='Synthetic shapes made by the trusted fixture generator; not vehicle parts.')


def scan_comparison(fixtures, runs, scan001_bracket, out):
    path = fresh(out / 'scan-002-vs-scan-001.png')
    reference = Solid(fixtures / 'bracket/part.stl')
    meshes = [('splat and closing (scan-001 code), no normals', load_stl(scan001_bracket), ORANGE),
              ('scan-002, oriented normals', load_stl(runs / 'scan-002/part.stl'), BLUE)]
    figure, axes = plt.subplots(2, 1, figsize=(9.5, 7.6), dpi=128, facecolor=BG, gridspec_kw={'height_ratios': [10, 4.6]})
    # Top: x-z section through the mounting hole.
    extent = (8.5, 21.5, -0.5, 9.5)
    frame(axes[0], extent, 'x (mm)', 'z (mm)', 'Section y = 0 through the 6.4 mm mounting hole')
    show_fill(axes[0], reference.fill('y', 0.0, extent, 0.04), extent, '#c9d4da')
    for _, tris, colour in meshes:
        segs, _ = cut(tris, 'y', 0.0)
        axes[0].plot(segs[:, [0, 2]].T, segs[:, [1, 3]].T, color=colour, lw=1.6, zorder=3)
    # Bottom: the rib at z = 14, drawn with y across so the 13 mm rib lies flat.
    extent = (-19.5, -3.5, 3.6, 7.2)
    frame(axes[1], extent, 'y (mm)', 'x (mm)', 'Section z = 14 through the 0.8 mm rib')
    rib = reference.fill('z', 14.0, (3.6, 7.2, -19.5, -3.5), 0.02)
    show_fill(axes[1], rib.T, extent, '#c9d4da')
    for _, tris, colour in meshes:
        segs, _ = cut(tris, 'z', 14.0)
        axes[1].plot(segs[:, [1, 3]].T, segs[:, [0, 2]].T, color=colour, lw=1.6, zorder=3)
    figure.legend(handles=[Patch(color='#c9d4da', label='reference solid')] +
                  [plt.Line2D([], [], color=c, lw=1.6, label=n) for n, _, c in meshes],
                  loc='lower center', ncol=3, frameon=False, fontsize=9)
    figure.suptitle('The same bracket scan, reconstructed with and without normals', color=INK, fontsize=12.5)
    figure.tight_layout(rect=(0, 0.05, 1, 0.96))
    figure.savefig(path, facecolor=BG); plt.close(figure)
    receipt(path, {'bracket/part.stl': fixtures / 'bracket/part.stl', 'scan-002/part.stl': runs / 'scan-002/part.stl',
                   'scan-001-on-bracket/part.stl': scan001_bracket},
            view='planar sections of the actual meshes; reference filled by winding number',
            scan001_on_bracket='scan-001 case code run on bracket/scan.xyz with the development runner '
                               '(not isolated, not part of the verification receipt)')


def gusset(fixtures, runs, out):
    path = fresh(out / 'dfam-002-gusset.png')
    cases = [('Before: 12 mm flat underside', Solid(fixtures / 'bracket/part.stl')),
             ('After dfam-002: gusset with a 50 deg underside', Solid(runs / 'dfam-002/part.stl'))]
    extent = (-23, -2, 14, 41)
    figure, axes = plt.subplots(1, 2, figsize=(9.6, 6.0), dpi=128, facecolor=BG)
    for axis, (title, solid) in zip(axes, cases):
        frame(axis, extent, 'x (mm)', 'z (mm), build direction up', title)
        tris = solid.tris
        normals = outward_normals(tris)
        zmin = tris[:, :, 2].min()
        flagged = (normals[:, 2] < -COS45) & (tris[:, :, 2].mean(1) > zmin + 0.45)
        segs, faces = cut(tris, 'y', 0.0)
        show_fill(axis, solid.fill('y', 0.0, extent, 0.05), extent, '#c9d4da')
        for subset, colour, width in ((~flagged[faces], SOLID, 1.2), (flagged[faces], OVERHANG, 2.8)):
            s = segs[subset]
            axis.plot(s[:, [0, 2]].T, s[:, [1, 3]].T, color=colour, lw=width, solid_capstyle='round', zorder=3)
        area = (0.5 * np.linalg.norm(np.cross(tris[:, 1] - tris[:, 0], tris[:, 2] - tris[:, 0]), axis=1))
        lip = flagged & (tris[:, :, 0].mean(1) > -18.5) & (tris[:, :, 0].mean(1) < -5.5) & (tris[:, :, 2].mean(1) > 20)
        axis.text(0.04, 0.04, f'downward area under the lip: {area[lip].sum():.0f} mm2', transform=axis.transAxes,
                  color=INK, fontsize=9.5, bbox=dict(facecolor='white', edgecolor=GRID, boxstyle='round,pad=0.4'))
    figure.legend(handles=[plt.Line2D([], [], color=SOLID, lw=1.2, label='section at y = 0'),
                           plt.Line2D([], [], color=OVERHANG, lw=2.8, label='facing within 45 deg of straight down')],
                  loc='lower center', ncol=2, frameon=False, fontsize=9)
    figure.suptitle('dfam-002: a gusset replaces the unsupported lip underside', color=INK, fontsize=12.5)
    figure.tight_layout(rect=(0, 0.06, 1, 0.95))
    figure.savefig(path, facecolor=BG); plt.close(figure)
    receipt(path, {'bracket/part.stl': fixtures / 'bracket/part.stl', 'dfam-002/part.stl': runs / 'dfam-002/part.stl'},
            view='planar section y = 0 of the actual meshes, filled by winding number; facets classified by outward normal',
            overhang_rule='normal z < -cos 45 deg, above the 0.45 mm plate band, as in dfam-native/Checker')


def manifold_panel(axis, solid, plane, value, extent, title, labels=()):
    frame(axis, extent, *(('x (mm)', 'z (mm)') if plane == 'y' else ('y (mm)', 'z (mm)')), title)
    show_fill(axis, solid.fill(plane, value, extent, 0.08), extent, INK)
    for x, y, text in labels:
        axis.annotate(text, (x, y), color=INK, fontsize=8.5, ha='center', va='center', annotation_clip=False,
                      bbox=dict(facecolor='white', edgecolor=GRID, boxstyle='round,pad=0.25'), zorder=4)


def infill(runs, out, frames=24):
    png, gif = fresh(out / 'infill-002-sections.png'), fresh(out / 'infill-002-section-sweep.gif')
    solid = Solid(runs / 'infill-002/part.stl')
    figure, axes = plt.subplots(1, 2, figsize=(11, 5.0), dpi=128, facecolor=BG,
                                gridspec_kw={'width_ratios': [52, 38]})
    manifold_panel(axes[0], solid, 'y', 9.0, (-26, 26, -1, 31),
                   'Section y = 9: two openings through the top, two channels',
                   [(8, 15, 'channels')])
    manifold_panel(axes[1], solid, 'x', 8.0, (-19, 19, -1, 31), 'Section x = 8: the channel network',
                   [(-8, 15, 'riser'), (5, 22, 'top run'), (2, 8, 'blind branch')])
    figure.suptitle('infill-002: D-sheet lattice, 1.5 mm skin and 2 mm channel sleeves (material dark)',
                    color=INK, fontsize=12)
    figure.tight_layout(rect=(0, 0.02, 1, 0.93))
    figure.savefig(png, facecolor=BG); plt.close(figure)

    images = []
    for value in np.linspace(-16, 16, frames):
        figure, axis = plt.subplots(figsize=(6, 4.2), dpi=110, facecolor=BG)
        manifold_panel(axis, solid, 'y', float(value), (-26, 26, -1, 31), f'infill-002, section y = {value:+.1f} mm')
        figure.text(0.5, 0.01, 'Exact cuts of the verified STL · synthetic fixture', ha='center', color=MUTED, fontsize=8)
        figure.tight_layout(rect=(0, 0.03, 1, 1))
        figure.canvas.draw()
        images.append(Image.fromarray(np.asarray(figure.canvas.buffer_rgba())).convert('RGB'))
        plt.close(figure)
    images[0].save(gif, save_all=True, append_images=images[1:] + images[-2:0:-1], duration=140, loop=0,
                   optimize=True, disposal=2)
    for path in (png, gif):
        receipt(path, {'infill-002/part.stl': runs / 'infill-002/part.stl'},
                view='planar sections filled by winding number',
                **({'frames': 2 * frames - 2, 'frame_ms': 140, 'sweep_mm': [-16, 16]} if path == gif else {}))


def pockets(runs, out):
    path = fresh(out / 'debug-002-pockets.png')
    cases = [('Broken: closed 2 mm floor, 118 deg points', runs / 'debug-002-broken/part.stl'),
             ('Corrected: open to the plate side, 80 deg points', runs / 'debug-002/part.stl')]
    extent = (-16, 8, -2, 18)
    pixel = 0.05
    figure, axes = plt.subplots(1, 2, figsize=(10, 4.9), dpi=128, facecolor=BG)
    for axis, (title, stl) in zip(axes, cases):
        frame(axis, extent, 'x (mm)', 'z (mm), build direction up', title)
        mesh = Solid(stl)
        segs, _ = cut(mesh.tris, 'y', 0.0)
        solid = mesh.fill('y', 0.0, extent, pixel)
        show_fill(axis, solid, extent, '#c9d4da')
        axis.plot(segs[:, [0, 2]].T, segs[:, [1, 3]].T, color=SOLID, lw=1.0, zorder=3)
        # Air not reachable from the frame edge in this section is drawn as trapped powder.
        labels, _ = ndimage.label(~solid)
        edge = np.unique(np.concatenate([labels[0], labels[-1], labels[:, 0], labels[:, -1]]))
        trapped = (~solid) & ~np.isin(labels, edge)
        show_fill(axis, trapped, extent, ORANGE, 0.85)
        axis.text(0.04, 0.93, f'sealed in this section: {trapped.sum() * pixel ** 2:.0f} mm2', transform=axis.transAxes,
                  color=INK, fontsize=9.5, va='top', bbox=dict(facecolor='white', edgecolor=GRID, boxstyle='round,pad=0.4'))
    figure.legend(handles=[Patch(color='#c9d4da', label='material, section y = 0'),
                           Patch(color=ORANGE, alpha=0.85, label='enclosed cavity: powder stays in the part')],
                  loc='lower center', ncol=2, frameon=False, fontsize=9)
    figure.suptitle('debug-002: a closed floor turns every pocket into a powder trap', color=INK, fontsize=12.5)
    figure.tight_layout(rect=(0, 0.07, 1, 0.95))
    figure.savefig(path, facecolor=BG); plt.close(figure)
    receipt(path, {'debug-002-broken/part.stl': cases[0][1], 'debug-002/part.stl': cases[1][1]},
            view='planar section y = 0; sealed regions by 2D flood fill from the frame edge, for display. '
                 'The 3D enclosed-void measure is the checker\'s.')


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--fixtures', type=Path, required=True)
    parser.add_argument('--runs', type=Path, required=True)
    parser.add_argument('--scan001-bracket', type=Path, required=True)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    fixture_families(args.fixtures, args.out)
    scan_comparison(args.fixtures, args.runs, args.scan001_bracket, args.out)
    gusset(args.fixtures, args.runs, args.out)
    infill(args.runs, args.out)
    pockets(args.runs, args.out)


if __name__ == '__main__':
    main()
