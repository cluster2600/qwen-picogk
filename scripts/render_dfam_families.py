"""Render the fixture-family and second-round case figures, with provenance receipts.

Inputs are the fixtures generated by the trusted checker, the output STLs of a
native verification run and, for one comparison, scan-001's published code
run on the bracket cloud outside the verifier. Section outlines are exact
planar cuts of the actual meshes; section fills classify raster points by the
generalised winding number of the same mesh (libigl), which is robust to
mesh vertices lying in the cutting plane. 3D views use a vertex-clustering
display proxy that every receipt records.
Geometry is never edited. Existing figures are never overwritten.

    python scripts/render_dfam_families.py --fixtures work/dfam-fixtures \
        --runs work/dfam-runs/strict-v3-20261019 \
        --scan001-bracket PATH/part.stl --out docs/visuals/dfam
"""
